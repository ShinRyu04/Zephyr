/* Kutip gaya berkas ini: kutip tunggal, escape bila isinya memuat kutip tunggal. */
const kutip = (s) =>
  s.includes("'")
    ? `"${s.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`
    : `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

let isi = readFileSync(berkas, 'utf8');

let totalDitambah = 0;
for (const [kode, tabelnya] of Object.entries(T)) {
  const huruf = kode.toUpperCase();
  const awalBlok = isi.indexOf(`const ${huruf}: Dict = {`);
  if (awalBlok < 0) {
    console.error(`  LEWAT  blok ${huruf} tidak ditemukan`);
    continue;
  }
  const tutup = isi.indexOf('\n};', awalBlok);
  if (tutup < 0) {
    console.error(`  LEWAT  penutup blok ${huruf} tidak ditemukan`);
    continue;
  }
  /* Lewati yang sudah ada, supaya skrip ini aman dijalankan dua kali. */
  const badan = isi.slice(awalBlok, tutup);
  const baru = Object.entries(tabelnya).filter(([k]) => !badan.includes(kutip(k) + ':'));
  if (!baru.length) {
    console.log(`  ${huruf}: sudah lengkap`);
    continue;
  }
  const entriBaru = baru.map(([k, v]) => `  ${kutip(k)}: ${kutip(v)},`).join('\n');
  isi = isi.slice(0, tutup) + '\n' + entriBaru + isi.slice(tutup);
  totalDitambah += baru.length;
  console.log(`  ${huruf}: +${baru.length} entri`);
}

writeFileSync(berkas, isi, { encoding: 'utf8' });
console.log(`\nTotal ${totalDitambah} entri ditambahkan.`);
