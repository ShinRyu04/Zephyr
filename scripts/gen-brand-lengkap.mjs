function pathDariSimple(nama) {
  const svg = readFileSync(join(dirSimple, `${nama}.svg`), 'utf8');
  const m = svg.match(/<path d="([^"]+)"/);
  if (!m) throw new Error(`tidak ada path di ${nama}.svg`);
  return m[1];
}

async function pathDariLobe(nama) {
  const url = `https://unpkg.com/@lobehub/icons-static-svg@${VERSI_LOBE}/icons/${nama}.svg`;
  const res = await fetch(url);
  if (!res.ok) throw new Error(`HTTP ${res.status}`);
  const svg = await res.text();
  const m = svg.match(/<path d="([^"]+)"/);
  if (!m) throw new Error('tidak ada path');
  return m[1];
}

const entri = {};
const gagal = [];

for (const [fam, src] of Object.entries(PETA)) {
  try {
    entri[fam] = {
      d: src.simple ? pathDariSimple(src.simple) : await pathDariLobe(src.lobe),
      warna: src.warna ?? null,
    };
  } catch (e) {
    gagal.push(`${fam}: ${e.message}`);
  }
}

