/*
 * Generate the file-icon table from material-icon-theme.
 *
 * The lookup follows VS Code's own order, because that order is what makes
 * `.ts` resolve to the TypeScript mark and `package.json` to the npm cube:
 *
 *   1. exact file name        (package.json, Dockerfile, .gitignore)
 *   2. full extension chain   (d.ts, d.mts, tar.gz) — longest first
 *   3. single extension       (ts, json, png)
 *   4. language id            (from the editor's own language detection)
 *   5. the generic file icon
 *
 * The mapping tables are also kept in separate objects: they overlap on key
 * names ("ts" is both an extension and a folder name), and writing them as one
 * object let the folder entry overwrite the extension entry — which is how
 * every .ts file ended up drawn with a folder icon.
 *
 * Re-run after bumping material-icon-theme:
 *   node scripts/gen-file-icons.mjs
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(ROOT, 'node_modules', 'material-icon-theme');
const OUT_MAP = join(ROOT, 'src', 'lib', 'fileIconMap.ts');

if (!existsSync(SRC)) {
  console.error('material-icon-theme tidak terpasang. Jalankan: npm i -D material-icon-theme');
  process.exit(1);
}

const manifest = JSON.parse(readFileSync(join(SRC, 'dist', 'material-icons.json'), 'utf8'));
const defs = manifest.iconDefinitions ?? {};

/*
 * Only the dark-theme variants are used: the app draws icons on a dark surface
 * in both themes, and the theme's `_light` twins are the same art tuned for a
 * white background.
 */
const bersihkan = (nama) => String(nama ?? '').replace(/_light$/, '');

const dipakai = new Set();

/** Resolves a manifest value to an icon definition name, or null. */
const ambil = (nama) => {
  const stem = bersihkan(nama);
  if (!stem || !defs[stem]) return null;
  dipakai.add(stem);
  return stem;
};

const fileExt = {};
for (const [ext, nama] of Object.entries(manifest.fileExtensions ?? {})) {
  const stem = ambil(nama);
  if (stem) fileExt[ext.toLowerCase()] = stem;
}

const fileName = {};
for (const [nama, ikon] of Object.entries(manifest.fileNames ?? {})) {
  const stem = ambil(ikon);
  if (stem) fileName[nama.toLowerCase()] = stem;
}

const folderName = {};
for (const [nama, ikon] of Object.entries(manifest.folderNames ?? {})) {
  const stem = ambil(ikon);
  if (stem) folderName[nama.toLowerCase()] = stem;
}

const langId = {};
for (const [id, nama] of Object.entries(manifest.languageIds ?? {})) {
  const stem = ambil(nama);
  if (stem) langId[id.toLowerCase()] = stem;
}

const folderIkon = ambil(manifest.folder) ?? 'folder';
const folderBuka = ambil(manifest.folderExpanded) ?? folderIkon;
const fileIkon = ambil(manifest.file) ?? 'file';

/*
 * Every SVG the tables reference is inlined as a string.
 *
 * The "@" list renders a dozen rows at once and a virtualised editor gutter can
 * render more; one fetch per row would cost more than carrying the bytes in the
 * bundle, and the set is bounded by what the manifest references.
 */
const svgDari = (stem) => {
  const def = defs[stem];
  const src = def?.src ? join(SRC, def.src) : join(SRC, 'icons', `${stem}.svg`);
  if (!existsSync(src)) return null;
  return readFileSync(src, 'utf8')
    // The theme sets width/height per file; the app sizes them from CSS.
    .replace(/\s(width|height)="[^"]*"/g, '')
    .replace(/\n\s*/g, '')
    .trim();
};

const stems = [...dipakai].sort();
const ikonSvg = {};
for (const s of stems) {
  const svg = svgDari(s);
  if (svg) ikonSvg[s] = svg;
}

const objek = (nama, obj, komentar) =>
  `/** ${komentar} */\nexport const ${nama}: Record<string, string> = {\n` +
  Object.entries(obj)
    .map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`)
    .join('\n') +
  '\n};\n';

const out = `/*
 * GENERATED by scripts/gen-file-icons.mjs — do not edit by hand.
 *
 * Icons from material-icon-theme (MIT). The lookup tables are the theme's own
 * mappings, kept in separate objects because they overlap on key names.
 */

/** Icon name -> inline SVG markup. */
export const IKON_SVG: Record<string, string> = {
${Object.entries(ikonSvg)
  .map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`)
  .join('\n')}
};

${objek('IKON_EXT', fileExt, 'Extension (lowercase, no dot) -> icon name.')}
${objek('IKON_NAMA', fileName, 'Exact file name (lowercase) -> icon name. Checked before the extension.')}
${objek('IKON_FOLDER_NAMA', folderName, 'Folder name (lowercase) -> icon name.')}
${objek('IKON_LANG', langId, 'Editor language id -> icon name. Last resort before the generic file.')}

/** Folder icons, closed and open, and the generic file fallback. */
export const IKON_FOLDER = ${JSON.stringify(folderIkon)};
export const IKON_FOLDER_BUKA = ${JSON.stringify(folderBuka)};
export const IKON_FILE = ${JSON.stringify(fileIkon)};
`;

writeFileSync(OUT_MAP, out, 'utf8');

console.log(`  ikon SVG   : ${Object.keys(ikonSvg).length}`);
console.log(`  ekstensi   : ${Object.keys(fileExt).length}`);
console.log(`  nama file  : ${Object.keys(fileName).length}`);
console.log(`  nama folder: ${Object.keys(folderName).length}`);
console.log(`  bahasa     : ${Object.keys(langId).length}`);
console.log(`  cek: ts=${fileExt.ts ?? '-'} tsx=${fileExt.tsx ?? '-'} d.ts=${fileExt['d.ts'] ?? '-'}`);
console.log(`  cek: php=${fileExt.php ?? '-'} py=${fileExt.py ?? '-'} md=${fileExt.md ?? '-'}`);
console.log(`  ditulis    : ${OUT_MAP.replace(ROOT, '.')}`);
