// Generates src/lib/modelBrandIcons.ts.
//
// Sources, in order of preference:
//   1. simple-icons (installed, CC0) - official marks, but OpenAI's is absent
//      from the package (trademark takedown), so it cannot cover everything.
//   2. @lobehub/icons-static-svg (CDN) - covers the families simple-icons is
//      missing, same 24x24 path-only format.
//
// Only the path data is copied, and only for the families the catalogue lists.
// Unknown ids keep the generic dot.
//
// Run: node scripts/gen-brand-icons.mjs

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const akar = join(dirname(fileURLToPath(import.meta.url)), '..');
const dirSimple = join(akar, 'node_modules/simple-icons/icons');

/*
 * Family -> source + brand colour.
 *
 * `warna: null` means the brand is monochrome by design and the mark should
 * follow the UI text colour, so it stays legible in both themes.
 */
const PETA = {
  gemini: { simple: 'googlegemini', warna: '#8E75B2' },
  claude: { simple: 'claude', warna: '#D97757' },
  gpt: { lobe: 'openai', warna: null },
  deepseek: { simple: 'deepseek', warna: '#4D6BFE' },
  grok: { simple: 'x', warna: null },
  llama: { simple: 'meta', warna: '#0866FF' },
  mistral: { simple: 'mistralai', warna: '#FA520F' },
  qwen: { simple: 'qwen', warna: '#615CED' },
  kimi: { simple: 'moonshotai', warna: null },
  ollama: { simple: 'ollama', warna: null },
  lmstudio: { simple: 'lmstudio', warna: null },
  huggingface: { simple: 'huggingface', warna: '#FFD21E' },
  perplexity: { simple: 'perplexity', warna: '#1FB8CD' },
  copilot: { lobe: 'githubcopilot', warna: null },
  codex: { lobe: 'codex', warna: null },
};

function pathDariSimple(nama) {
  const svg = readFileSync(join(dirSimple, `${nama}.svg`), 'utf8');
  const m = svg.match(/<path d="([^"]+)"/);
  if (!m) throw new Error(`no path in ${nama}.svg`);
  return m[1];
}

async function pathDariLobe(nama) {
  const url = `https://unpkg.com/@lobehub/icons-static-svg@1.95.1/icons/${nama}.svg`;
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${nama}: HTTP ${res.status}`);
  const svg = await res.text();
  const m = svg.match(/<path d="([^"]+)"/);
  if (!m) throw new Error(`no path in lobe ${nama}.svg`);
  return m[1];
}

const baris = [];
for (const [fam, src] of Object.entries(PETA)) {
  let d;
  try {
    d = src.simple ? pathDariSimple(src.simple) : await pathDariLobe(src.lobe);
  } catch (e) {
    console.log(`  SKIP ${fam}: ${e.message}`);
    continue;
  }
  baris.push(
    `  ${fam}: {\n    d: '${d}',\n    warna: ${src.warna ? `'${src.warna}'` : 'null'},\n  },`
  );
}

const isi = `// GENERATED by scripts/gen-brand-icons.mjs - do not edit by hand.
//
// Official brand marks for the model families in the catalogue. Path data is
// taken from simple-icons (CC0) and @lobehub/icons-static-svg, both 24x24, so
// every mark shares one viewBox and scales cleanly.
//
// \`warna: null\` is deliberate, not missing data: those brands are drawn in a
// single neutral tone and look wrong tinted.

export interface BrandMark {
  d: string;
  /** Brand colour, or null to inherit the surrounding text colour. */
  warna: string | null;
}

export const BRAND_MARKS: Record<string, BrandMark> = {
${baris.join('\n')}
};
`;

writeFileSync(join(akar, 'src/lib/modelBrandIcons.ts'), isi, 'utf8');
console.log(`  wrote src/lib/modelBrandIcons.ts (${baris.length} marks)`);
