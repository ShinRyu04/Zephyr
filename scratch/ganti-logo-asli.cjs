const fs = require('fs');
const p = 'src/lib/modelCatalog.tsx';
let s = fs.readFileSync(p, 'utf8');

const awal = s.indexOf('const logo = PROVIDER_BY_ID.get(id)?.logo ?? (id as LogoId);');
const akhir = s.indexOf('});\r\n\r\n/*\r\n * Per-model mark.');
if (awal < 0 || akhir < 0) {
  console.error('anchor tidak ketemu', awal, akhir);
  process.exit(1);
}
console.log('membuang', akhir - awal, 'karakter switch lama');

const baru = `const logo = PROVIDER_BY_ID.get(id)?.logo ?? (id as LogoId);

  /*
   * Official mark, when the brand table has one.
   *
   * \`modelBrandIcons.ts\` already ships 34 official marks (simple-icons CC0 and
   * @lobehub/icons-static-svg, generated by \`scripts/gen-brand-lengkap.mjs\`) on a
   * 24x24 grid. Hand-drawing approximations beside them was the mistake: two
   * shapes for one brand in one app, and the approximations were visibly wrong —
   * a letter Z for Z.ai, two circles for PPIO, a triangle for Vercel.
   *
   * The table keys are brand FAMILIES (gemini, gpt, claude, glm, ...), not
   * provider ids, because one family can be served by several providers: "Kimi
   * Global" and "Kimi CN" are both \`kimi\`, "Z.ai" and "Bigmodel" are both \`glm\`.
   * This map is the single place that says which family a provider wears.
   */
  const keluarga: Record<string, string> = {
    gemini: 'gemini',
    openai: 'gpt',
    anthropic: 'claude',
    deepseek: 'deepseek',
    xai: 'grok',
    mistral: 'mistral',
    groq: 'groq',
    openrouter: 'openrouter',
    ollama: 'ollama',
    zai: 'glm',
    bigmodel: 'glm',
    minimax: 'minimax',
    'minimax-cn': 'minimax',
    kimi: 'kimi',
    'kimi-cn': 'kimi',
    byteplus: 'bytedance',
    novita: 'together',
    aws: 'bedrock',
    azure: 'azure',
    vercel: 'vertexai',
    volcano: 'bytedance',
    alibaba: 'qwen',
    tencent: 'tencent',
    gmi: 'together',
    mimo: 'mimo',
    siliconflow: 'qwen',
    gitee: 'antgroup',
    ppio: 'together',
  };

  const kunci = keluarga[logo as string] ?? (logo as string);
  const mark = BRAND_MARKS[kunci];

  if (mark) {
    /*
     * One path, one viewBox (24), one colour rule.
     *
     * \`warna: null\` means the brand is monochrome BY DESIGN (OpenAI, Grok,
     * Vercel) — those follow the surrounding text colour instead of being
     * tinted, which is what the generator recorded and what the brands do.
     */
    return (
      <svg {...p} viewBox="0 0 24 24" aria-label={id}>
        <path d={mark.d} fill={mark.warna ?? 'currentColor'} />
      </svg>
    );
  }

  /* Fallback for a provider the brand table does not know yet: a neutral tile
     rather than a wrong logo. */
  return (
    <svg {...p} aria-label={id}>
      <rect
        x="2.6"
        y="2.6"
        width="10.8"
        height="10.8"
        rx="2.4"
        fill="none"
        stroke="currentColor"
        strokeWidth="1.3"
      />
    </svg>
  );
`;

s = s.slice(0, awal) + baru + s.slice(akhir);
fs.writeFileSync(p, s);
console.log('ProviderLogo diganti ke BRAND_MARKS');
