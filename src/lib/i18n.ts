let EXTRA: Record<string, Record<string, string>> = {};

export async function muatKamusTambahan(): Promise<void> {
  try {
    const m = await import('./i18n-extra');
    EXTRA = m.EXTRA as unknown as Record<string, Record<string, string>>;
  } catch {
    EXTRA = {};
  }
}

export function translate(lang: string, key: string): string {

  // The target-language dictionary ALWAYS wins. SRC is only the English dictionary for keys
  // whose original text is Indonesian; it used to be that SRC was checked first, so any
  // key present in SRC always showed English even when the JA/KO/
  // ES/… translation was already available - that was the cause of "switch language and it is still English
  // Inggris".
  const own = EXTRA[lang]?.[key] ?? DICTS[lang]?.[key];
  if (own !== undefined) return own;
  const src = SRC[key];
  if (src !== undefined) return lang === 'id' ? key : src;
  // Indonesian first, then Indonesian.
  //
  // DICTS.id was at one point the last resort, and that was dangerous: a key that only
  // exists in the ID dictionary leaked into ALL languages. As long as its value happened to be
  // English nothing looked broken - until a key was written in
  // Indonesian, and that menu showed up in Indonesian in the English, Japanese,
  // and so on without a trace. id is still included so that no text is
  // vanish altogether, but the order is now correct.
  //
  // URUTAN INI DIPERBAIKI. Dulu baris terakhirnya:
  //
  //   return EXTRA.en?.[key] ?? DICTS.en[key] ?? DICTS.id[key] ?? key;
  //
  // `DICTS.en` di baris itu adalah kamus DASAR - bukan kamus Inggris
  // terjemahan. Ia memuat pasangan seperti `'Berjalan': 'Running'`, yaitu
  // kunci Indonesia dengan nilai Inggris. Jadi untuk kunci yang HANYA ada di
  // kamus dasar, SEMUA bahasa jatuh ke situ dan menampilkan bahasa Inggris.
  //
  // Gejalanya halus dan menyesatkan: di bahasa Indonesia, badge status muncul
  // "Running" padahal kamusnya ada dan sudah diterjemahkan; di bahasa Jepang
  // pun "Running". Terlihat seperti kunci yang hilang, padahal kuncinya ada -
  // yang salah cuma urutan pencariannya.
  //
  // Sekarang bahasa aktif dicoba pada kamus dasarnya LEBIH DULU, dan bahasa
  // Inggris hanya dipakai sebagai jaring terakhir saat benar-benar tidak ada
  // apa pun.
  return (
    EXTRA[lang]?.[key] ??
    DICTS[lang]?.[key] ??
    DICTS.en[key] ??
    DICTS.id[key] ??
    key
  );
}

/**
 * Release note / changelog text can be multi-language: if `notes` is a JSON
 * object { en, id, ja, ... } pick according to the active language (falling back to en). If it is
 * not JSON, return it as-is (the old behaviour).
 */
export function catatanUntukBahasa(notes: string | null | undefined, lang: string): string {
  if (!notes) return '';
  const s = notes.trim();
  if (!s.startsWith('{')) return notes;
  try {
    const obj = JSON.parse(s) as Record<string, string>;
    if (obj && typeof obj === 'object' && !Array.isArray(obj)) {
      return obj[lang] ?? obj.en ?? Object.values(obj)[0] ?? notes;
    }
  } catch {
    /* not JSON - use it as-is */
  }
  return notes;
}

export function useT(): (key: string) => string {
  const lang = useStore((s) => s.settings.general.uiLang);
  return (key: string) => translate(lang, key);
}

export function tx(key: string): string {
  return translate(useStore.getState().settings.general.uiLang, key);
}

export function tf(key: string, isi: Record<string, string | number>): string {
  let teks = tx(key);
  for (const [k, v] of Object.entries(isi)) {
    teks = teks.split(`{${k}}`).join(String(v));
  }
  return teks;
}

export function useTf(): (key: string, isi: Record<string, string | number>) => string {
  const tr = useT();
  return (key, isi) => {
    let teks = tr(key);
    for (const [k, v] of Object.entries(isi)) {
      teks = teks.split(`{${k}}`).join(String(v));
    }
    return teks;
  };
}
