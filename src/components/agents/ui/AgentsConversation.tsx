import { AgentsComposer } from './AgentsComposer';
import { AgentsIcon, type AgentsIconName } from './AgentsIcon';
import { useAi } from '../../../lib/aiStore';

/**
 * The conversation view for the Agents window.
 *
 * Measured on the active-chat reference: the chat is NOT the full canvas. It is
 * a 520px card on the left — 16px corners, 16px inset — and the workspace panel
 * fills everything to its right. Its composer is 486px wide (520 minus the two
 * insets) with slightly shorter boxes than the centred one: 125px and 42px.
 *
 * The composer is pinned to the bottom of the card while the transcript scrolls
 * above it, so the newest message sits next to the field rather than leaving a
 * dead gap underneath.
 *
 * ## Why each reply is headed by name and closed by a feedback row
 *
 * The reference attributes every answer: a name above the text and a
 * "Generated by AI" line with copy / retry / like / dislike underneath. The
 * transcript used to print the role in uppercase ("AGENT"), which reads as a
 * form field, not as a speaker. The name shown is the real one for the model
 * that answered (falling back to "Assistant" when the message records no
 * model), so a chat that switched models mid-way does not credit the wrong
 * one.
 */
const PANEL_ACTIONS: { id: string; label: string; icon: AgentsIconName }[] = [
  { id: 'file', label: 'Open a file', icon: 'folder' },
  { id: 'browser', label: 'Open a browser', icon: 'search' },
  { id: 'terminal', label: 'Open a terminal', icon: 'panel' },
];

/** The label above a reply: the model that wrote it, as the reader sees it in
 *  the picker. `msg.model` is the stored id; an unknown id is shown verbatim
 *  rather than guessed at. */
function namaAgent(model?: string): string {
  if (!model) return 'Assistant';
  const id = model.includes('/') ? model.split('/').pop() ?? model : model;
  return id;
}

export function AgentsConversation({
  composerId,
  onPanelAction,
}: {
  composerId: string;
  onPanelAction?: (id: string) => void;
}) {
  const messages = useAi((s) => {
    const id = s.activeIds[composerId] ?? null;
    const sesi = s.sessions.find((x) => x.id === id);
    return sesi?.messages ?? [];
  });

  return (
    <div className="agx-conversation" data-testid="agx-conversation">
      <section
        className="agx-chat-card"
        data-testid="agx-chat-card"
        style={{ width: 520, borderRadius: 16 }}
      >
        <header className="agx-chat-card-head">Agent</header>

        <div className="agx-transcript" data-testid="agx-transcript">
          {messages.map((m) => (
            <article
              key={m.id}
              className={`agx-msg agx-msg-${m.role}`}
              data-testid={`agx-msg-${m.role}`}
            >
              <span className="agx-msg-role">
                {m.role === 'user' ? 'You' : namaAgent(m.model)}
              </span>
              <p className="agx-msg-text">{m.content}</p>
              {/*
                * Feedback row — assistant messages only.
                *
                * Retry is a real control: it re-runs the turn through the
                * store's own `regenerate`, which is what the shared panel's
                * retry does. Copy writes the reply to the clipboard through the
                * Tauri plugin (`navigator.clipboard` is denied in WebView2 when
                * the document is not focused — see AGENTS.md).
                */}
              {m.role === 'assistant' && (
                <div className="agx-msg-foot" data-testid={`agx-foot-${m.id}`}>
                  <span className="agx-msg-gen">Generated by AI</span>
                  <span className="agx-msg-actions">
                    <button
                      type="button"
                      className="agx-msg-act"
                      title="Copy"
                      aria-label="Copy"
                      data-testid={`agx-copy-${m.id}`}
                      onClick={() => {
                        void import('../../../lib/clipboard').then((x) =>
                          x.clipboardWrite(m.content),
                        );
                      }}
                    >
                      <svg viewBox="0 0 16 16" aria-hidden="true">
                        <rect x="5.4" y="5.4" width="7.4" height="7.4" rx="1.2" />
                        <path d="M10.6 5.4V4a1.2 1.2 0 0 0-1.2-1.2H4a1.2 1.2 0 0 0-1.2 1.2v5.4A1.2 1.2 0 0 0 4 10.6h1.4" />
                      </svg>
                    </button>
                    <button
                      type="button"
                      className="agx-msg-act"
                      title="Retry"
                      aria-label="Retry"
                      data-testid={`agx-retry-${m.id}`}
                      onClick={() => {
                        void import('../../../lib/aiStore').then((x) =>
                          x.useAi.getState().regenerate(composerId),
                        );
                      }}
                    >
                      <svg viewBox="0 0 16 16" aria-hidden="true">
                        <path d="M13 8a5 5 0 1 1-1.6-3.7" />
                        <path d="M13 2.6V5h-2.4" />
                      </svg>
                    </button>
                    <button
                      type="button"
                      className="agx-msg-act"
                      title="Good response"
                      aria-label="Good response"
                    >
                      <svg viewBox="0 0 16 16" aria-hidden="true">
                        <path d="M5.6 13.4V6.6l3-4.2a1.3 1.3 0 0 1 2.1 1.3L9.8 6.6h2.9a1.2 1.2 0 0 1 1.2 1.4l-.7 4.3a1.2 1.2 0 0 1-1.2 1H5.6z" />
                        <path d="M5.6 6.6H2.6v6.8h3" />
                      </svg>
                    </button>
                    <button
                      type="button"
                      className="agx-msg-act"
                      title="Bad response"
                      aria-label="Bad response"
                    >
                      <svg viewBox="0 0 16 16" aria-hidden="true">
                        <path d="M5.6 2.6v6.8l3 4.2a1.3 1.3 0 0 0 2.1-1.3l-.9-2.9h2.9a1.2 1.2 0 0 0 1.2-1.4l-.7-4.3a1.2 1.2 0 0 0-1.2-1H5.6z" />
                        <path d="M5.6 9.4H2.6V2.6h3" />
                      </svg>
                    </button>
                  </span>
                </div>
              )}
            </article>
          ))}
        </div>

        <div className="agx-chat-card-composer" style={{ padding: '0 16px 16px' }}>
          <AgentsComposer composerId={composerId} variant="docked" />
        </div>
      </section>

      <aside className="agx-panel" data-testid="agx-panel" aria-label="Workspace panel">
        <header className="agx-panel-head">Start here</header>
        <ul className="agx-panel-list">
          {PANEL_ACTIONS.map((a) => (
            <li key={a.id}>
              <button
                type="button"
                className="agx-panel-row"
                data-testid={`agx-panel-${a.id}`}
                onClick={() => onPanelAction?.(a.id)}
              >
                <span className="agx-panel-icon">
                  <AgentsIcon name={a.icon} size={15} />
                </span>
                <span>{a.label}</span>
              </button>
            </li>
          ))}
        </ul>
      </aside>
    </div>
  );
}
